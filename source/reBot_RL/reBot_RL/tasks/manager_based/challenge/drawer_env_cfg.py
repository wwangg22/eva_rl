"""Drawer ordering (articulated object + irreversible precedence) for the reBot arm.

Pull a drawer open by its handle, then put a block inside. Two things here that the
pick-and-place task never asks for:

* **Articulated interaction.** The gripper has to follow a kinematic constraint it does not
  know, applying force along the drawer's slide axis and nowhere else. A policy that simply
  "wants" to move off that manifold stalls or rips off the handle.
* **Irreversible precedence.** The block cannot go in until the drawer is open, and the
  carry reward is *hard-gated* to zero until then -- there is no smooth distance gradient
  bridging the two stages, unlike carrying an object toward an always-open basket.

The handle is a 20 mm bar standing 22 mm off the drawer face so the fingers can straddle it
**side-on**; this arm has no top-down grasp below z = 0.19 m and could not reach over a lip
(docs/CHALLENGE_SUITE.md C1). The cabinet stands on a 45 mm plinth at x = 0.265, both of
which are forced by measurement rather than taste: the usable TCP band is x ~ 0.22..0.26 and
the gripper cannot be positioned below z = 44 mm at all, so at table height the handle would
have been permanently out of reach (``scripts/analysis/tcp_floor.py``). The drawer still
travels *toward* the robot as it opens, into easier space.

The asset is generated by ``scripts/challenge/author_drawer_usd.py``.
"""

